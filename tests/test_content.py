class BuzzwordClusters(unittest.TestCase):
    CLUSTER = (
        "<p>A seamless, robust platform to elevate your workflow.</p>\n"
        "<p>Leverage cutting-edge, innovative tools.</p>\n"
        "<p>Effortless and intuitive.</p>\n"
    )

    def test_a_cluster_of_buzzwords_in_one_file_is_one_finding(self):
        findings = [f for f in file_findings(self.CLUSTER) if f["category"] == "buzzword"]
        self.assertEqual(len(findings), 1)
        self.assertEqual(findings[0]["match"], "buzzword cluster")
        self.assertEqual(findings[0]["line"], 1)
        self.assertIn("seamless", findings[0]["detail"])
        self.assertIn("cutting-edge", findings[0]["detail"])

    def test_the_count_is_of_distinct_words(self):
        text = "<p>Seamless. Seamless. Seamless. Seamless. Seamless.</p>\n"
        self.assertEqual([f for f in file_findings(text) if f["category"] == "buzzword"], [])

    def test_the_same_word_on_four_lines_is_still_one_word(self):
        text = "<p>Seamless.</p>\n<p>Seamless.</p>\n<p>Seamless.</p>\n<p>Seamless.</p>\n"
        self.assertEqual([f for f in file_findings(text) if f["category"] == "buzzword"], [])

    def test_a_few_buzzwords_are_not_a_cluster(self):
        text = "<p>A robust way to streamline your day.</p>\n<p>It is fast.</p>\n"
        self.assertEqual([f for f in file_findings(text) if f["category"] == "buzzword"], [])

    def test_buzzwords_alone_are_never_line_findings(self):
        self.assertEqual(categories("<p>A seamless, robust, innovative, cutting-edge platform.</p>"), [])

    def test_the_cluster_is_in_the_report_with_its_words(self):
        report = scan.report(file_findings(self.CLUSTER))
        self.assertIn("Buzzword cluster (1)", report)
        self.assertIn("buzzword cluster", report)
        self.assertIn("seamless", report)


class EmDashes(unittest.TestCase):
    def test_a_file_thick_with_em_dashes_is_one_finding(self):
        text = "".join(f"<p>Line {i} — and more — again.</p>\n" for i in range(4))
        findings = [f for f in file_findings(text) if f["category"] == "dash"]
        self.assertEqual(len(findings), 1)
