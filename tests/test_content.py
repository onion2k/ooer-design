class ScannedFiles(unittest.TestCase):
    def test_markdown_content_is_scanned_but_repo_docs_are_not(self):
        with tempfile.TemporaryDirectory() as root:
            os.makedirs(os.path.join(root, "src", "content"))
            with open(os.path.join(root, "src", "content", "about.md"), "w") as f:
                f.write("In today's fast-paced world, we deliver.\n")
            with open(os.path.join(root, "README.md"), "w") as f:
                f.write("In today's fast-paced world, we deliver.\n")
            with open(os.path.join(root, "CHANGELOG.md"), "w") as f:
                f.write("In today's fast-paced world, we deliver.\n")
            files = {f["file"] for f in scan.scan(root)}
        self.assertEqual(files, {os.path.join("src", "content", "about.md")})


