class SlopFixture(unittest.TestCase):
    """A synthetic generated landing page, assembled from the tells the
    research describes, so that the whole catalogue gets a run end to end."""

    FIXTURE = os.path.join(os.path.dirname(__file__), "fixtures", "slop")

    def findings(self):
        return scan.scan(self.FIXTURE)

    def test_it_hits_nearly_every_category(self):
        hit = {f["category"] for f in self.findings()}
        missing = set(scan.CATEGORIES) - hit
        # Beige, cream-and-terracotta and imagery are the light-mode tells; the fixture is dark.
        self.assertEqual(missing, {"beige", "tasteful", "imagery"})

    def test_the_whole_section_order_is_read_past_the_nav(self):
        order = [f for f in self.findings() if f["match"] == "stock section order"][0]
        self.assertEqual(order["detail"], "hero → logos → features → how it works → testimonials → pricing → faq → cta → footer")

    def test_a_glow_is_not_also_a_soft_shadow(self):
        mine = [f["category"] for f in self.findings() if "rgba(99, 102, 241" in f["match"]]
        self.assertIn("glow", mine)
        self.assertNotIn("shadow", mine)

    def test_one_phrase_is_one_finding(self):
        pivots = [f for f in self.findings() if f["category"] == "copy" and "not just" in f["match"]]
        self.assertEqual(len(pivots), 1)
        arrows = [f for f in self.findings() if f["category"] == "cta" and f["line"] == 18]
        self.assertEqual(len(arrows), 1)

    def test_no_detail_spans_lines(self):
        for finding in self.findings():
            self.assertNotIn("\n", finding.get("detail", ""), finding)
