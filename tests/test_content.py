"""Tests for the content tells: the words, placeholders and chrome of a
generated site, as opposed to its colours and shapes.

Each tell is checked both ways, as in test_scan.py. The left-alone cases
matter more here, because copy is where a scanner is most tempted to cry
wolf: "seamless" in a sentence is a hint, not a verdict, so the scanner only
reports vocabulary once a file has a cluster of it.

Run with: python3 -m unittest discover tests
"""

import datetime
import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "skills", "polish"))

import scan  # noqa: E402


def categories(line):
    return [category for category, _ in scan.scan_line(line)]


def file_findings(text, name="page.html"):
    with tempfile.TemporaryDirectory() as root:
        with open(os.path.join(root, name), "w") as f:
            f.write(text)
        return scan.scan(root)


class Placeholders(unittest.TestCase):
    def test_lorem_ipsum_is_found(self):
        self.assertIn("placeholder", categories("<p>Lorem ipsum dolor sit amet, consectetur.</p>"))

    def test_placeholder_names_and_companies_are_found(self):
        for text in ("<h1>Your Company</h1>", "<p>Company Name Here</p>", "<span>John Doe</span>", "<span>Jane Smith</span>"):
            self.assertIn("placeholder", categories(text), text)

    def test_reserved_example_addresses_are_found(self):
        for text in ('placeholder="you@example.com"', "<a>hello@yourcompany.com</a>", "Call +1 (555) 123-4567", "123 Main Street, Anytown"):
            self.assertIn("placeholder", categories(text), text)

    def test_bracketed_fill_ins_are_found(self):
        self.assertIn("placeholder", categories("<blockquote>[Insert testimonial here]</blockquote>"))
        self.assertIn("placeholder", categories("<p>— [Your Name]</p>"))

    def test_placeholder_image_services_are_found(self):
        for text in (
            '<img src="https://placehold.co/600x400">',
            '<img src="https://via.placeholder.com/150">',
            'src="/placeholder.svg?height=400&width=600"',
            '<img src="https://i.pravatar.cc/100">',
            'src="https://randomuser.me/api/portraits/women/1.jpg"',
            'src="https://ui-avatars.com/api/?name=Sarah"',
            'src="https://api.dicebear.com/7.x/avataaars/svg"',
        ):
            self.assertIn("placeholder", categories(text), text)

    def test_default_page_titles_are_found(self):
        for text in ("<title>Vite + React</title>", "<title>Create Next App</title>", "<title>Document</title>", 'content="Generated by create next app"'):
            self.assertIn("placeholder", categories(text), text)

    def test_a_stale_copyright_year_is_found(self):
        last_year = datetime.date.today().year - 1
        self.assertIn("placeholder", categories(f"<p>© {last_year} Acme Inc. All rights reserved.</p>"))
        self.assertIn("placeholder", categories(f"&copy; 2019-{last_year} Acme"))

    def test_this_years_copyright_is_left_alone(self):
        year = datetime.date.today().year
        self.assertEqual(categories(f"<p>© {year} Panic & Wonder</p>"), [])
        self.assertEqual(categories(f"© 2019–{year} Chris Neale"), [])

    def test_coming_soon_and_text_goes_here_are_found(self):
        self.assertIn("placeholder", categories("<p>Coming soon</p>"))
        self.assertIn("placeholder", categories("<p>Description goes here</p>"))

    def test_a_real_name_and_address_are_left_alone(self):
        self.assertEqual(categories("<p>Chris Neale, 14 Vine Street, Bristol</p>"), [])
        self.assertEqual(categories("<a>chris@usablehq.com</a>"), [])


