    def test_a_few_em_dashes_are_left_alone(self):
        text = "<p>One — two.</p>\n<p>Three — four.</p>\n"
        self.assertEqual([f for f in file_findings(text) if f["category"] == "dash"], [])

    def test_an_em_dash_in_a_button_or_heading_is_a_finding_on_its_own(self):
        self.assertIn("dash", categories("<button>Start free — no card needed</button>"))
        self.assertIn("dash", categories("<h1>Plan — build — ship</h1>"))
